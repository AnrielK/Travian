#!/usr/bin/env python3
"""
Night look of the village views (Legends "night mode"): body[data-theme=night] swaps the day pictures of the
background, the resource fields, the buildings, the wall and the harbour for those of img_ltr/themes/night. Legends
ships these rules for its own markup only, and the day rules of the template styles and of the OpenVillage adapter are
more specific, so this script copies every rule of the pack's styles that shows a day picture with a night counterpart,
prefixed with "html body[data-theme=night]" (one element and one attribute more than the day rule, so it wins).

Writes css/openvillage-t46-night.css of the pack, loaded after openvillage-t46.css (see ov_gpack_adapter_links).

Usage: python3 -I scripts/gpack/night-theme.py [graphic pack mainPage dir]
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SOURCES = ['default_compressed0.css', 'default_compressed1.css', 'default_compressed2.css', 'default_compressed3.css',
           'default_compressed4.css', 'legends_ltr.css', 'openvillage-t46-tribes.css', 'openvillage-t46.css']
URL = re.compile(r"""url\(\s*(['"]?)([^'")]+)\1\s*\)""")
DAY = [('img_ltr/layout/background2019/', 'img_ltr/themes/night/background/'),
       ('img_ltr/themes/default/', 'img_ltr/themes/night/'),
       ('img_ltr/g/buildings/', 'img_ltr/themes/night/buildings/')]
PREFIX = 'html body[data-theme=night]'


def blocks(css):
    """(media or None, selector, declarations) of the top-level rules and of the rules inside @media."""
    i, n = 0, len(css)
    while i < n:
        j = css.find('{', i)
        if j < 0:
            return
        head = css[i:j].strip()
        if head.startswith('@media'):
            depth, k = 1, j + 1
            while depth and k < n:
                depth += {'{': 1, '}': -1}.get(css[k], 0)
                k += 1
            for _, sel, body in blocks(css[j + 1:k - 1]):
                yield head, sel, body
            i = k
        elif head.startswith('@'):
            depth, k = 1, j + 1
            while depth and k < n:
                depth += {'{': 1, '}': -1}.get(css[k], 0)
                k += 1
            i = k
        else:
            k = css.find('}', j)
            yield None, head.split(';')[-1].strip(), css[j + 1:k]
            i = k + 1


def night_picture(pack, rel):
    """Path (relative to css/) of the night counterpart of a day picture, None when there is none."""
    path = os.path.normpath(os.path.join('css', rel)).replace(os.sep, '/')
    for day, night in DAY:
        if path.startswith(day):
            stem, ext = os.path.splitext(night + path[len(day):])
            for e in [ext, '.webp', '.jpg', '.png']:
                if os.path.isfile(os.path.join(pack, stem + e)):
                    return '../' + stem + e
    return None


def night_selector(sel, picture):
    """The day selector under the night prefix; building pictures only in the village view (the build window keeps
    the day picture, as in Legends), nothing inside the page content."""
    sel = sel.strip()
    if 'data-theme' in sel or 'season' in sel or '#content' in sel:
        return None
    if '/buildings/' in picture and '#villageContent' not in sel and '#background' not in sel:
        m = re.search(r'(^|[\s>])img\.', sel)
        if not m:
            return None
        sel = sel[:m.start() + len(m.group(1))] + '#villageContent ' + sel[m.start() + len(m.group(1)):]
    m = re.match(r'(html\s+)?body(?=[.#\[:\s>~+]|$)', sel)
    return PREFIX + sel[m.end():] if m else PREFIX + ' ' + sel


def main():
    pack = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, 'sections/gpack/legends655/mainPage')
    out = ['@charset "UTF-8";',
           '/* Generated by scripts/gpack/night-theme.py: the night pictures of the village views for body[data-theme=night]',
           '   (LayoutT46.php), as copies of the day rules of the styles before this one. */']
    count = 0
    for fn in SOURCES:
        f = os.path.join(pack, 'css', fn)
        if not os.path.isfile(f):
            continue
        for media, sel, body in blocks(open(f, encoding='utf-8', errors='replace').read()):
            m = re.search(r'background(?:-image)?\s*:([^;]*url\([^;]*)', body)
            if not m:
                continue
            urls = [u for _, u in URL.findall(m.group(1))]
            if not urls or any(u.startswith('data:') for u in urls):
                continue
            night = [night_picture(pack, u) for u in urls]
            if not any(night):
                continue
            picture = next(nu for nu in night if nu)
            sels = [s for s in (night_selector(s, picture) for s in sel.split(',')) if s]
            if not sels:
                continue
            image = ','.join('url(%s)' % (nu or u) for u, nu in zip(urls, night))
            rule = ','.join(sels) + '{background-image:' + image + '}'
            out.append(media + '{' + rule + '}' if media else rule)
            count += 1
    target = os.path.join(pack, 'css', 'openvillage-t46-night.css')
    with open(target, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write('\n'.join(out) + '\n')
    print('%d rules -> %s' % (count, os.path.relpath(target, ROOT)))


if __name__ == '__main__':
    main()
